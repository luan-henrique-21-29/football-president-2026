import fs from 'node:fs';
import assert from 'node:assert/strict';
const index=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('src/app.js','utf8');
const shell=fs.readFileSync('src/shell-v2.js','utf8');
const css=fs.readFileSync('game-shell-v2.css','utf8');
const a11y=fs.readFileSync('src/accessibility-layer.js','utf8');
const quick=fs.readFileSync('src/quick-center.js','utf8');
assert.match(index,/game-shell-v2\.css\?v=/,'fixed game shell stylesheet must be loaded');
assert.match(app,/dashboard-v8\.js/,'compact dashboard must be active');
assert.match(app,/bindAccessibility/,'accessibility controls must be bound');
assert.match(app,/bindQuickCenter/,'quick center must be bound');
assert.match(shell,/id=\\?"gameContent\\?"/,'main game content needs a focusable landmark');
assert.match(shell,/gcp-skip-link/,'skip link must exist');
assert.match(shell,/quickCenterLayer\(\)/,'quick center layer must be rendered');
assert.match(shell,/accessibilityLayer\(\)/,'accessibility layer must be rendered');
assert.match(css,/html,body\{[^}]*overflow:hidden!important/s,'browser document scrolling must be locked');
assert.match(css,/\.content\{[^}]*overflow:auto!important/s,'game content must scroll internally');
assert.match(css,/overscroll-behavior:contain/,'internal scrolling must not chain to the browser');
assert.match(css,/:focus-visible/,'visible keyboard focus must be styled');
assert.match(css,/prefers-reduced-motion:reduce/,'reduced-motion preference must be respected');
assert.match(a11y,/Alt\+1 Início/,'keyboard shortcuts must be documented');
assert.match(a11y,/document\.fullscreenElement/,'fullscreen control must toggle');
assert.match(quick,/PRÓXIMO|partida|gcp-quick-match/i,'quick center must expose match utility');
console.log('ui shell smoke tests passed');
